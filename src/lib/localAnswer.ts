import { findCountry } from "./countries";
import type { Bot } from "./store";

/**
 * Built-in engine: answers visa / recruitment / documentation questions from the
 * app's own knowledge base, so the desk works with no API key at all.
 */
export function localAnswer(bot: Bot, text: string, countryCode?: string): string {
  const c = findCountry(countryCode);
  const q = text.toLowerCase();
  const want = (words: string[]) => words.some((w) => q.includes(w));
  const flag = c ? `${c.flag} ${c.name} (${c.bn})` : "কোনো দেশ নির্বাচন করা হয়নি";

  const head = `*${bot.name}* · বিল্ট-ইন ইঞ্জিন${c ? ` · ${flag}` : ""}`;

  if (bot.id === "docs" || want(["passport", "পাসপোর্ট", "document", "ডকুমেন্ট", "attest", "pdf", "স্ক্যান"])) {
    return [
      head,
      "",
      `*১. পাসপোর্ট থেকে যা পড়া হবে*`,
      `নাম (surname, given names), পাসপোর্ট নম্বর, জাতীয়তা, জন্মতারিখ, লিঙ্গ, জন্মস্থান, ইস্যু ও মেয়াদ, MRZ লাইন।`,
      "",
      `*২. যা যাচাই করব*`,
      `মেয়াদ ভ্রমণের পরে অন্তত ৬ মাস, সব ডকুমেন্টে নামের বানান এক, ছবি বায়োমেট্রিক, MRZ পড়া যায়।`,
      "",
      `*৩. প্যাকেটের ক্রম*`,
      `আবেদন ফর্ম → পাসপোর্ট বায়ো পেজ → ছবি → ব্যাংক স্টেটমেন্ট → চাকরি/ব্যবসার প্রমাণ → আমন্ত্রণ বা অফার → বীমা → থাকার প্রমাণ → টিকিট → কভার লেটার → চেকলিস্ট।`,
      "",
      `*৪. অ্যাটেস্টেশন চেইন (বাংলাদেশ)*`,
      `নোটারি → পররাষ্ট্র মন্ত্রণালয় → গন্তব্য দূতাবাস।`,
      "",
      c ? `*৫. ${c.name} এর জন্য দরকার*` : `*৫. দেশ নির্বাচন করুন*`,
      c ? c.needs.map((n, i) => `${i + 1}. ${n}`).join("\n") : "ড্যাশবোর্ডে দেশ বেছে নিলে ঠিক কী কী লাগবে লিখে দেব।",
      "",
      `_ফাইল দিলে আমি ঘর ধরে ধরে পড়ে প্যাকেট বানাব।_`,
    ].join("\n");
  }

  if (bot.id === "visa" || want(["job", "চাকরি", "recruit", "রিক্রুট", "employer", "কর্মী", "demand"])) {
    return [
      head,
      "",
      `*ধাপ ১ — চাহিদা*`,
      `দেশ, ট্রেড, বেতার, কর্মঘণ্টা, চুক্তির মেয়াদ, থাকা-খাওয়া, কোটা, লাইসেন্স নম্বর।`,
      "",
      `*ধাপ ২ — শর্টলিস্ট*`,
      `ট্রেড মিল, অভিজ্ঞতা, ভাষা, বয়স, পাসপোর্টের মেয়াদ — এই পাঁচটায় ০-১০০ নম্বর দিয়ে ফিট স্কোর।`,
      "",
      `*ধাপ ৩ — কাগজ*`,
      `পাসপোর্ট, ছবি, এমপ্লয়ার ফরম্যাটে CV, অভিজ্ঞতার সনদ, স্কিল সার্টিফিকেট, মেডিকেল, পুলিশ ক্লিয়ারেন্স, ডিমান্ড লেটার, পাওয়ার অব অ্যাটর্নি, এজেন্সি লাইসেন্স।`,
      "",
      `*ধাপ ৪ — ট্র্যাকিং*`,
      `সোর্সিং → স্ক্রিনিং → ইন্টারভিউ → সিলেকশন → মেডিকেল → ভিসা ফাইল → ভিসা অনুমোদন → ফ্লাইং।`,
      "",
      c ? `*এখন ${c.name} এর জন্য*: ${c.portal}, প্রসেসিং ${c.days} দিন, ক্যাটাগরি ${c.types.join(", ")}।` : `*দেশ বেছে নিন* — নিয়ম ও পোর্টাল সেই অনুযায়ী দেব।`,
      "",
      `_ভিসার প্রতিশ্রুতি নয় — সিলেকশন ও অনুমোদন এমপ্লয়ার ও দূতাবাসের হাতে।_`,
    ].join("\n");
  }

  if (bot.id === "browser" || want(["apply", "আবেদন", "portal", "ফর্ম", "fee", "ফি", "appointment", "সাবমিট", "submit"])) {
    return [
      head,
      "",
      `*১. ক্যাটাগরি*`,
      c ? `${c.types.join(" / ")} — প্রোফাইল দেখে একটা বেছে নেব।` : `দেশ বেছে নিন, তারপর ক্যাটাগরি ঠিক করব।`,
      "",
      `*২. পোর্টাল*`,
      c ? `${c.portal} — অফিসিয়াল সাইটেই সব তথ্য যাচাই করব।` : `অফিসিয়াল পোর্টাল ব্যবহার করব, তৃতীয় পক্ষ নয়।`,
      "",
      `*৩. ফর্ম ফিল*`,
      `পাসপোর্ট থেকে নাম, নম্বর, জন্মতারিখ; বাকি তথ্য আপনার দেওয়া প্রোফাইল থেকে; প্রতিটা ঘরের পাশে উৎস লিখে দেব।`,
      "",
      `*৪. আপলোড*`,
      c ? c.needs.join(", ") : `পাসপোর্ট, ছবি, আর্থিক প্রমাণ, চাকরি/ব্যবসার প্রমাণ।`,
      "",
      `*৫. অ্যাপয়েন্টমেন্ট ও ফি*`,
      `ফি পোর্টালে দেখানো অঙ্ক, রসিদ সংরক্ষণ, অ্যাপয়েন্টমেন্ট স্লট বুকিং।`,
      "",
      `_সাবমিটের আগে সব ঘর আপনার সামনে একবার দেখাব — অনুমতি ছাড়া জমা দেব না।_`,
    ].join("\n");
  }

  return [
    head,
    "",
    `আমি অফিসের তিনটা ডেস্ক চালাই — *Visa Filing*, *Global Recruitment*, *Documentation*।`,
    "",
    c ? `এখন aktif: ${flag} · পোর্টাল ${c.portal} · প্রসেসিং ${c.days} দিন।` : `ড্যাশবোর্ডে দেশ বেছে নিন।`,
    "",
    `যা করতে পারি:`,
    `১. পাসপোর্ট/ডকুমেন্ট থেকে তথ্য পড়ে কেস বানানো`,
    `২. দেশ অনুযায়ী কাগজের চেকলিস্ট ও ফি`,
    `৩. আবেদন ফর্ম ঘর ধরে পূরণ`,
    `৪. রিক্রুটমেন্ট শর্টলিস্ট ও চুক্তি`,
    `৫. পুরো PDF প্যাকেট`,
    "",
    `শুরু করতে লিখুন: “পাসপোর্ট দিয়ে আবেদন শুরু করো” অথবা ড্যাশবোর্ডে ফাইল আপলোড করুন।`,
  ].join("\n");
}
