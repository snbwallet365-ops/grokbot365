import { makePdf, downloadUrl } from "./pdf";
import { findCountry } from "./countries";
import type { Applicant, Employer } from "./store";

export interface PackageInput {
  applicant: Applicant;
  employer: Employer;
  countryCode?: string;
  visaType?: string;
}

const line = (label: string, value?: string) => (value && value.trim() ? `${label}: ${value.trim()}` : `${label}: —`);

export function buildPackageMarkdown(p: PackageInput): string {
  const c = findCountry(p.countryCode);
  const a = p.applicant;
  const e = p.employer;
  const today = new Date().toLocaleDateString("en-GB");

  return `# Visa application package

Prepared by World Vision Consultancy · N Space desk · ${today}

${c ? `Destination: ${c.name} (${c.code})  \nEmbassy / portal: ${c.portal}  \nTypical processing: ${c.days} days` : "Destination: —"}
${p.visaType ? `Visa type: ${p.visaType}` : ""}

## 1. Cover letter

To
The Visa Officer
${c ? `${c.name} embassy / consulate` : "The Embassy"}
Subject: Application for ${p.visaType || "a visa"} — ${a.fullName || "applicant"}

Dear Sir or Madam,

I am ${a.fullName || "the applicant"}, holder of ${a.nationality || "—"} passport number ${a.passportNo || "—"}, born on ${a.dob || "—"}. I am applying for ${p.visaType || "a visa"}${c ? ` to ${c.name}` : ""}.

${e.company ? `I am currently employed as ${a.occupation || e.jobTitle || "an employee"} at ${e.company}${e.address ? `, ${e.address}` : ""}. My employer supports this application and confirms that my position is secure and my leave is approved for the duration of the trip.` : `I am ${a.occupation || "self-employed"} and my income and ties to my home country are documented in the attached papers.`}

All information in this application is true and complete to the best of my knowledge, and I will comply with the conditions of the visa.

Yours faithfully,
${a.fullName || "—"}
Passport ${a.passportNo || "—"} · ${a.phone || ""} · ${a.email || ""}

## 2. Applicant summary

${line("Full name", a.fullName)}
${line("Surname / Given names", [a.surname, a.givenNames].filter(Boolean).join(" / "))}
${line("Passport number", a.passportNo)}
${line("Nationality", a.nationality)}
${line("Date of birth", a.dob)}
${line("Sex", a.sex)}
${line("Passport expiry", a.expiry)}
${line("Place of issue", a.issuePlace)}
${line("Occupation", a.occupation)}
${line("Phone", a.phone)}
${line("Email", a.email)}
${line("Address", a.address)}

## 3. Employment and sponsorship letter

${e.company || "—"}
${e.address || ""}
${[e.phone, e.email].filter(Boolean).join(" · ")}

Date: ${today}

This letter confirms that ${a.fullName || "the applicant"}${e.jobTitle ? ` works with us as ${e.jobTitle}` : ""}${e.contractStart ? ` since ${e.contractStart}` : ""}${e.salary ? `, with a monthly remuneration of ${e.salary}` : ""}.

We have granted leave for travel and confirm that the applicant's employment will continue after the trip. We support the visa application and take responsibility for the accuracy of the information above.

${e.contactPerson || "—"}
${e.designation || "Authorised signatory"}
${e.registrationNo ? `Company registration: ${e.registrationNo}` : ""}

## 4. Document checklist

${c ? c.needs.map((r: string) => `- ${r}`).join("\n") : "- Passport (6+ months validity)\n- Photograph\n- Bank statement\n- Employment letter\n- Itinerary"}

Additional for this file:
- Passport first page (clear scan)
- Passport photograph to spec
- Bank statement, last 6 months, stamped
- Employment or sponsorship letter (page 3 of this package)
- Accommodation and flight reservation
- Travel insurance covering the full stay

## 5. Declaration

I declare that the information given above and in the attached documents is true, complete and accurate, and that I am aware of the conditions of entry and stay.

Signature: ____________________  Date: ${today}

---
Generated by N Space · grokbot365.vercel.app`;
}

export function downloadPackage(p: PackageInput) {
  const md = buildPackageMarkdown(p);
  const { url, filename } = makePdf(`Visa package — ${p.applicant.fullName || "applicant"}`, md);
  downloadUrl(url, filename);
  return { md, filename };
}
